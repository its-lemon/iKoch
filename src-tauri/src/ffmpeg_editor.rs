/// Resolves `ffmpeg` or `ffprobe` sidecar binary:
/// 1) next to current executable (`<tool>-x86_64-pc-windows-msvc.exe` or `<tool>.exe`),
/// 2) inside `src-tauri/binaries/` (`CARGO_MANIFEST_DIR`),
/// 3) fallback on system `PATH`.
pub fn resolve_sidecar_binary(tool: &str) -> Result<PathBuf, String> {
    let target_name = format!("{tool}-x86_64-pc-windows-msvc.exe");
    let plain_name = format!("{tool}.exe");

    if let Ok(exe_path) = std::env::current_exe() {
        if let Some(exe_dir) = exe_path.parent() {
            for candidate_name in [&target_name, &plain_name] {
                let candidate = exe_dir.join(candidate_name);
                if candidate.is_file() {
                    return Ok(candidate);
                }
            }
        }
    }

    let manifest_bin_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("binaries");
    for candidate_name in [&target_name, &plain_name] {
        let candidate = manifest_bin_dir.join(candidate_name);
        if candidate.is_file() {
            return Ok(candidate);
        }
    }

    // Fallback to PATH search (works cleanly if ffmpeg/ffprobe are globally installed).
    if let Ok(path_var) = std::env::var("PATH") {
        for dir in std::env::split_paths(&path_var) {
            let candidate = dir.join(&plain_name);
            if candidate.is_file() {
                return Ok(candidate);
            }
        }
    }

    Err(format!(
        "Could not locate sidecar binary '{target_name}' or '{plain_name}'"
    ))
}

fn hidden_cmd(bin: &Path) -> Command {
    let mut cmd = Command::new(bin);
    cmd.creation_flags(CREATE_NO_WINDOW);
    cmd
}

/// Probes video and audio track metadata of `video_path` using `ffprobe`.
pub fn probe_media_streams(video_path: &Path) -> Result<ProbedMediaInfo, String> {
    if !video_path.exists() {
        return Err(format!("Media file '{}' does not exist", video_path.display()));
    }
    let ffprobe = resolve_sidecar_binary("ffprobe")?;
    let output = hidden_cmd(&ffprobe)
        .args(["-v", "error", "-print_format", "json", "-show_format", "-show_streams"])
        .arg(video_path)
        .output()
        .map_err(|e| format!("Failed to spawn ffprobe: {e}"))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        return Err(format!("ffprobe failed: {stderr}"));
    }

    let root: serde_json::Value = serde_json::from_slice(&output.stdout)
        .map_err(|e| format!("Parse ffprobe JSON failed: {e}"))?;

    let duration_sec = root
        .get("format")
        .and_then(|f| f.get("duration"))
        .and_then(|d| d.as_str())
        .and_then(|s| s.parse::<f64>().ok())
        .unwrap_or(0.0);

    let mut width = 0u32;
    let mut height = 0u32;
    let mut video_codec = "h264".to_string();
    let mut audio_streams = Vec::new();
    let mut audio_ordinal = 0usize;

    if let Some(streams) = root.get("streams").and_then(|s| s.as_array()) {
        for st in streams {
            let codec_type = st.get("codec_type").and_then(|v| v.as_str()).unwrap_or("");
            if codec_type == "video" && width == 0 {
                width = st.get("width").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
                height = st.get("height").and_then(|v| v.as_u64()).unwrap_or(0) as u32;
                video_codec = st
                    .get("codec_name")
                    .and_then(|v| v.as_str())
                    .unwrap_or("h264")
                    .to_string();
            } else if codec_type == "audio" {
                let stream_index = st.get("index").and_then(|v| v.as_u64()).unwrap_or(0) as usize;
                let codec_name = st
                    .get("codec_name")
                    .and_then(|v| v.as_str())
                    .unwrap_or("aac")
                    .to_string();
                let sample_rate = st
                    .get("sample_rate")
                    .and_then(|v| v.as_str())
                    .and_then(|s| s.parse::<u32>().ok())
                    .unwrap_or(48_000);
                let channels = st.get("channels").and_then(|v| v.as_u64()).unwrap_or(2) as u16;
                let handler_name = st
                    .get("tags")
                    .and_then(|t| t.get("handler_name").or_else(|| t.get("title")))
                    .and_then(|v| v.as_str())
                    .map(str::trim);

                let (track_kind, label) = classify_probed_audio_stream(handler_name, audio_ordinal);
                audio_streams.push(ProbedAudioStream {
                    stream_index,
                    ordinal: audio_ordinal,
                    track_kind,
                    label,
                    codec_name,
                    sample_rate,
                    channels,
                });
                audio_ordinal += 1;
            }
        }
    }

    Ok(ProbedMediaInfo {
        duration_sec,
        width,
        height,
        video_codec,
        audio_streams,
    })
}

fn classify_probed_audio_stream(handler_name: Option<&str>, ordinal: usize) -> (TrackKind, String) {
    if let Some(name) = handler_name {
        let lower = name.to_ascii_lowercase();
        if lower.contains("mixed") {
            return (TrackKind::AudioMixed, "Mixed Audio".to_string());
        }
        if lower.contains("game") {
            return (TrackKind::AudioGame, "Game Audio".to_string());
        }
        if lower.contains("mic") {
            return (TrackKind::AudioMic, "Microphone".to_string());
        }
        if lower.contains("secondary") {
            return (TrackKind::AudioSecondary, "Secondary Audio".to_string());
        }
    }
    match ordinal {
        0 => (TrackKind::AudioMixed, "Mixed Audio".to_string()),
        1 => (TrackKind::AudioGame, "Game Audio".to_string()),
        2 => (TrackKind::AudioMic, "Microphone".to_string()),
        _ => (TrackKind::AudioSecondary, "Secondary Audio".to_string()),
    }
}

/// Generates a crisp preview thumbnail JPEG at `timestamp_sec`.
pub fn generate_thumbnail_jpg(
    video_path: &Path,
    output_jpg: &Path,
    timestamp_sec: f64,
) -> Result<PathBuf, String> {
    if let Some(parent) = output_jpg.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|e| format!("create_dir_all failed: {e}"))?;
        }
    }
    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let ts_arg = format!("{:.3}", timestamp_sec.max(0.0));
    let output = hidden_cmd(&ffmpeg)
        .args(["-y", "-hide_banner", "-loglevel", "error", "-ss", &ts_arg, "-i"])
        .arg(video_path)
        .args(["-frames:v", "1", "-vf", "scale=640:-2", "-q:v", "3"])
        .arg(output_jpg)
        .output()
        .map_err(|e| format!("Failed to launch ffmpeg thumbnail: {e}"))?;

    if !output.status.success() {
        return Err(format!(
            "ffmpeg thumbnail failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(output_jpg.to_path_buf())
}

/// Decodes one audio track via `ffmpeg` into `8 kHz mono s16le` on stdout and reduces it
/// into `buckets` normalized amplitude peaks (`0.0..=1.0`).
pub fn extract_waveform_peaks(
    video_path: &Path,
    audio_stream_ordinal: usize,
    buckets: usize,
) -> Result<Vec<f32>, String> {
    let target_buckets = buckets.clamp(16, 2000);
    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let map_arg = format!("0:a:{audio_stream_ordinal}");
    let output = hidden_cmd(&ffmpeg)
        .args(["-hide_banner", "-loglevel", "error", "-i"])
        .arg(video_path)
        .args([
            "-map", &map_arg, "-vn", "-ac", "1", "-ar", "8000", "-f", "s16le", "pipe:1",
        ])
        .output()
        .map_err(|e| format!("Failed to launch ffmpeg waveform extractor: {e}"))?;

    if !output.status.success() {
        return Err(format!(
            "ffmpeg waveform failed for stream {map_arg}: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }

    let sample_count = output.stdout.len() / 2;
    if sample_count == 0 {
        return Ok(vec![0.0; target_buckets]);
    }

    let mut samples = Vec::with_capacity(sample_count);
    for chunk in output.stdout[..sample_count * 2].chunks_exact(2) {
        let s = i16::from_le_bytes([chunk[0], chunk[1]]);
        samples.push((i32::from(s).abs() as f32) / 32_768.0);
    }

    let mut peaks = Vec::with_capacity(target_buckets);
    for i in 0..target_buckets {
        let start = (i * sample_count) / target_buckets;
        let end = (((i + 1) * sample_count) / target_buckets).max(start + 1).min(sample_count);
        let peak = samples[start..end].iter().copied().fold(0.0f32, f32::max);
        peaks.push(peak.clamp(0.0, 1.0));
    }
    Ok(peaks)
}

/// Prepares thumbnail JPEG, per-track waveform peaks, and copy-muxed `.m4a` stems inside `cache_dir`
/// for instant Stage 6 multi-track editor timelines.
pub fn prepare_editor_media(
    video_path: &Path,
    cache_dir: &Path,
    buckets: usize,
) -> Result<PreparedEditorMedia, String> {
    fs::create_dir_all(cache_dir).map_err(|e| format!("create_dir_all cache failed: {e}"))?;
    let probed = probe_media_streams(video_path)?;
    let stem = video_path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("clip");

    let thumb_path = ClipMetadata::thumbnail_path_for(video_path);
    let thumb_ts = if probed.duration_sec > 1.0 {
        (probed.duration_sec * 0.25).min(1.0)
    } else {
        0.0
    };
    generate_thumbnail_jpg(video_path, &thumb_path, thumb_ts)?;
    let sidecar = ClipMetadata::sidecar_path_for(video_path);
    if let Ok(mut meta) = load_clip_metadata(&sidecar) {
        if meta.thumbnail_path.as_ref().is_none_or(|p| !p.exists())
            || meta.thumbnail_path.as_ref() != Some(&thumb_path)
        {
            meta.thumbnail_path = Some(thumb_path.clone());
            let _ = save_clip_metadata(&meta);
        }
    }

    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let mut waveforms = Vec::with_capacity(probed.audio_streams.len());
    for st in &probed.audio_streams {
        let peaks = extract_waveform_peaks(video_path, st.ordinal, buckets)?;
        let stem_audio_path = cache_dir.join(format!("{stem}_track{}.m4a", st.ordinal));
        let map_arg = format!("0:a:{}", st.ordinal);
        let status = hidden_cmd(&ffmpeg)
            .args(["-y", "-hide_banner", "-loglevel", "error", "-i"])
            .arg(video_path)
            .args(["-map", &map_arg, "-vn", "-c:a", "copy", "-movflags", "+faststart"])
            .arg(&stem_audio_path)
            .output()
            .map_err(|e| format!("Failed to launch ffmpeg stem extract: {e}"))?;
        if !status.status.success() {
            warn!(
                "Stem audio extract warning for '{}': {}",
                map_arg,
                String::from_utf8_lossy(&status.stderr)
            );
        }
        waveforms.push(TrackWaveform {
            stream_ordinal: st.ordinal,
            kind: st.track_kind,
            label: st.label.clone(),
            peaks,
            stem_audio_path,
        });
    }

    Ok(PreparedEditorMedia {
        thumbnail_path: thumb_path,
        probed,
        waveforms,
    })
}

/// Extracts a lossless full-resolution PNG frame at `req.timestamp_sec`.
pub fn capture_frame_png(req: &FrameScreenshotRequest) -> Result<PathBuf, String> {
    if let Some(parent) = req.output_png_path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|e| format!("create_dir_all failed: {e}"))?;
        }
    }
    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let ts = format!("{:.3}", req.timestamp_sec.max(0.0));
    let out = hidden_cmd(&ffmpeg)
        .args(["-y", "-hide_banner", "-loglevel", "error", "-ss", &ts, "-i"])
        .arg(&req.source_path)
        .args(["-frames:v", "1"])
        .arg(&req.output_png_path)
        .output()
        .map_err(|e| format!("Failed to spawn ffmpeg screenshot: {e}"))?;

    if !out.status.success() {
        return Err(format!(
            "ffmpeg PNG screenshot failed: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(req.output_png_path.clone())
}

/// Executes lossless `-c copy` trim or fast mixdown matching [`TrimRequest`].
pub fn run_fast_trim(req: &TrimRequest) -> Result<PathBuf, String> {
    if req.end_sec <= req.start_sec {
        return Err("Trim end_sec must be greater than start_sec".to_string());
    }
    if let Some(parent) = req.output_path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|e| format!("create_dir_all failed: {e}"))?;
        }
    }

    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let probed = probe_media_streams(&req.source_path)?;
    let start_s = format!("{:.3}", req.start_sec.max(0.0));
    let dur_s = format!("{:.3}", (req.end_sec - req.start_sec).max(0.05));

    let mut cmd = hidden_cmd(&ffmpeg);
    cmd.args(["-y", "-hide_banner", "-loglevel", "error", "-ss", &start_s, "-t", &dur_s, "-i"])
        .arg(&req.source_path);

    match req.audio_mode {
        TrimAudioExportMode::KeepSeparateTracks => {
            cmd.args(["-map", "0:v:0", "-map", "0:a?", "-c", "copy", "-avoid_negative_ts", "make_zero"]);
        }
        TrimAudioExportMode::GameTrackOnly => {
            let ord = find_track_ordinal(&probed.audio_streams, TrackKind::AudioGame).unwrap_or(0);
            let map_a = format!("0:a:{ord}?");
            cmd.args(["-map", "0:v:0", "-map", &map_a, "-c", "copy", "-avoid_negative_ts", "make_zero"]);
        }
        TrimAudioExportMode::MicTrackOnly => {
            let ord = find_track_ordinal(&probed.audio_streams, TrackKind::AudioMic).unwrap_or(0);
            let map_a = format!("0:a:{ord}?");
            cmd.args(["-map", "0:v:0", "-map", &map_a, "-c", "copy", "-avoid_negative_ts", "make_zero"]);
        }
        TrimAudioExportMode::MixToSingleTrack => {
            let game_ord = find_track_ordinal(&probed.audio_streams, TrackKind::AudioGame);
            let mic_ord = find_track_ordinal(&probed.audio_streams, TrackKind::AudioMic);
            if let (Some(g), Some(m)) = (game_ord, mic_ord) {
                let gv = req.game_volume.clamp(0.0, 2.0);
                let mv = req.mic_volume.clamp(0.0, 2.0);
                let fc = format!(
                    "[0:a:{g}]volume={gv:.3}[ag];[0:a:{m}]volume={mv:.3}[am];[ag][am]amix=inputs=2:duration=longest:normalize=0[aout]"
                );
                cmd.args(["-filter_complex", &fc, "-map", "0:v:0", "-map", "[aout]", "-c:v", "copy", "-c:a", "aac", "-b:a", "192k"]);
            } else {
                cmd.args(["-map", "0:v:0", "-map", "0:a:0?", "-c", "copy"]);
            }
        }
    }

    cmd.args(["-movflags", "+faststart"]).arg(&req.output_path);
    let out = cmd.output().map_err(|e| format!("Failed to launch ffmpeg trim: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "ffmpeg trim failed: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    mark_edited_sidecar(&req.source_path, &req.output_path, false);
    Ok(req.output_path.clone())
}

/// Compresses a clip under a Discord upload preset size (`10 MiB` / `50 MiB` / custom MiB).
pub fn run_discord_compress(
    req: &DiscordCompressRequest,
    total_duration_sec: f64,
) -> Result<PathBuf, String> {
    let start = req.start_sec.unwrap_or(0.0).max(0.0);
    let end = req.end_sec.unwrap_or(total_duration_sec.max(0.5));
    let span = (end - start).max(0.5);

    let adv = AdvancedExportRequest {
        clip_id: req.clip_id,
        source_path: req.source_path.clone(),
        output_path: req.output_path.clone(),
        segments: vec![SegmentRange {
            start_sec: start,
            end_sec: end,
        }],
        playback_speed: 1.0,
        aspect_ratio: AspectRatioPreset::Original,
        text_overlays: Vec::new(),
        fade_in_sec: 0.0,
        fade_out_sec: 0.0,
        track_mix: vec![
            TrackMixSpec {
                kind: TrackKind::AudioGame,
                volume: req.game_volume,
                muted: false,
            },
            TrackMixSpec {
                kind: TrackKind::AudioMic,
                volume: req.mic_volume,
                muted: false,
            },
        ],
        discord_preset: Some(req.preset),
        export_gif: false,
        subclip_from_session: false,
        discord_webhook_url: None,
    };
    let _ = span;
    run_advanced_export(&adv)
}

/// Pure representation of the FFmpeg `filter_complex` graph produced by [`build_advanced_filter_graph`].
#[derive(Debug, Clone)]
pub struct BuiltFilterGraph {
    pub filter_complex: String,
    pub has_audio: bool,
    pub output_duration_sec: f64,
}

/// Builds a complete FFmpeg `filter_complex` graph implementing Split & Cut (`segments`),
/// playback speed (`0.25x..=4.0x`), `16:9` / `9:16` blurred / `1:1` framing, `drawtext`,
/// video/audio `fade`/`afade`, multi-track `amix`, and GIF palette generation.
pub fn build_advanced_filter_graph(
    req: &AdvancedExportRequest,
    probed: &ProbedMediaInfo,
) -> Result<BuiltFilterGraph, String> {
    let segments: Vec<SegmentRange> = if req.segments.is_empty() {
        vec![SegmentRange {
            start_sec: 0.0,
            end_sec: probed.duration_sec.max(0.1),
        }]
    } else {
        req.segments
            .iter()
            .filter(|s| s.end_sec > s.start_sec)
            .copied()
            .collect()
    };
    if segments.is_empty() {
        return Err("No valid segments with end_sec > start_sec".to_string());
    }

    let speed = f64::from(req.playback_speed.clamp(0.25, 4.0));
    let total_src_sec: f64 = segments.iter().map(|s| s.end_sec - s.start_sec).sum();
    let out_duration_sec = (total_src_sec / speed).max(0.05);

    let active_audio: Vec<(usize, f32)> = resolve_active_audio_mix(&req.track_mix, &probed.audio_streams);
    let has_audio = !req.export_gif && !active_audio.is_empty();

    let mut parts: Vec<String> = Vec::new();

    // 1. Mix source audio channels if present & not exporting GIF.
    if has_audio {
        if active_audio.len() == 1 {
            let (ord, vol) = active_audio[0];
            parts.push(format!("[0:a:{ord}]volume={vol:.3}[amix_src]"));
        } else {
            let mut mix_labels = String::new();
            for (i, &(ord, vol)) in active_audio.iter().enumerate() {
                parts.push(format!("[0:a:{ord}]volume={vol:.3}[am{i}]"));
                mix_labels.push_str(&format!("[am{i}]"));
            }
            parts.push(format!(
                "{mix_labels}amix=inputs={}:duration=longest:normalize=0[amix_src]",
                active_audio.len()
            ));
        }
    }

    // 2. Multi-segment Split & Cut + Concat.
    let seg_count = segments.len();
    if seg_count == 1 {
        let s = segments[0];
        parts.push(format!(
            "[0:v:0]trim=start={:.3}:end={:.3},setpts=PTS-STARTPTS[vcat]",
            s.start_sec.max(0.0),
            s.end_sec
        ));
        if has_audio {
            parts.push(format!(
                "[amix_src]atrim=start={:.3}:end={:.3},asetpts=PTS-STARTPTS[acat]",
                s.start_sec.max(0.0),
                s.end_sec
            ));
        }
    } else {
        let mut v_splits = String::new();
        let mut a_splits = String::new();
        for i in 0..seg_count {
            v_splits.push_str(&format!("[vs{i}]"));
            if has_audio {
                a_splits.push_str(&format!("[as{i}]"));
            }
        }
        parts.push(format!("[0:v:0]split={seg_count}{v_splits}"));
        if has_audio {
            parts.push(format!("[amix_src]asplit={seg_count}{a_splits}"));
        }

        let mut concat_inputs = String::new();
        for (i, seg) in segments.iter().enumerate() {
            parts.push(format!(
                "[vs{i}]trim=start={:.3}:end={:.3},setpts=PTS-STARTPTS[vt{i}]",
                seg.start_sec.max(0.0),
                seg.end_sec
            ));
            if has_audio {
                parts.push(format!(
                    "[as{i}]atrim=start={:.3}:end={:.3},asetpts=PTS-STARTPTS[at{i}]",
                    seg.start_sec.max(0.0),
                    seg.end_sec
                ));
                concat_inputs.push_str(&format!("[vt{i}][at{i}]"));
            } else {
                concat_inputs.push_str(&format!("[vt{i}]"));
            }
        }
        if has_audio {
            parts.push(format!("{concat_inputs}concat=n={seg_count}:v=1:a=1[vcat][acat]"));
        } else {
            parts.push(format!("{concat_inputs}concat=n={seg_count}:v=1:a=0[vcat]"));
        }
    }

    // 3. Speed adjustment on video + Aspect ratio preset.
    let speed_filter = if (speed - 1.0).abs() > 0.001 {
        format!("setpts=PTS/{speed:.4},")
    } else {
        String::new()
    };

    match req.aspect_ratio {
        AspectRatioPreset::Original => {
            parts.push(format!(
                "[vcat]{speed_filter}scale=trunc(iw/2)*2:trunc(ih/2)*2[vaspect]"
            ));
        }
        AspectRatioPreset::Square1x1 => {
            parts.push(format!(
                "[vcat]{speed_filter}crop='min(iw,ih)':'min(iw,ih)',scale=1080:1080[vaspect]"
            ));
        }
        AspectRatioPreset::Vertical9x16Blurred => {
            parts.push(format!(
                "[vcat]{speed_filter}split=2[vfg_in][vbg_in];\
                 [vbg_in]scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,boxblur=25:5,eq=brightness=-0.12[vbg];\
                 [vfg_in]scale=1080:-2:force_original_aspect_ratio=decrease[vfg];\
                 [vbg][vfg]overlay=(W-w)/2:(H-h)/2[vaspect]"
            ));
        }
    }

    // 4. Text overlays (drawtext) + Video Fade In / Fade Out.
    let mut v_post_ops: Vec<String> = Vec::new();
    for overlay in &req.text_overlays {
        if overlay.text.trim().is_empty() {
            continue;
        }
        v_post_ops.push(format_drawtext_filter(overlay));
    }
    if req.fade_in_sec > 0.01 {
        v_post_ops.push(format!("fade=t=in:st=0:d={:.3}", req.fade_in_sec.min(10.0)));
    }
    if req.fade_out_sec > 0.01 && out_duration_sec > f64::from(req.fade_out_sec) {
        let fade_start = (out_duration_sec - f64::from(req.fade_out_sec)).max(0.0);
        v_post_ops.push(format!(
            "fade=t=out:st={fade_start:.3}:d={:.3}",
            req.fade_out_sec.min(10.0)
        ));
    }

    if req.export_gif {
        let pre = if v_post_ops.is_empty() {
            String::new()
        } else {
            format!("{},", v_post_ops.join(","))
        };
        parts.push(format!(
            "[vaspect]{pre}fps=15,scale=640:-2:flags=lanczos,split[gs0][gs1];\
             [gs0]palettegen[gp];[gs1][gp]paletteuse[vout]"
        ));
    } else if v_post_ops.is_empty() {
        parts.push("[vaspect]null[vout]".to_string());
    } else {
        parts.push(format!("[vaspect]{}[vout]", v_post_ops.join(",")));
    }

    // 5. Audio speed (`atempo` chain) + Audio Fade In / Fade Out.
    if has_audio {
        let mut a_post_ops = atempo_filters(speed);
        if req.fade_in_sec > 0.01 {
            a_post_ops.push(format!("afade=t=in:st=0:d={:.3}", req.fade_in_sec.min(10.0)));
        }
        if req.fade_out_sec > 0.01 && out_duration_sec > f64::from(req.fade_out_sec) {
            let fade_start = (out_duration_sec - f64::from(req.fade_out_sec)).max(0.0);
            a_post_ops.push(format!(
                "afade=t=out:st={fade_start:.3}:d={:.3}",
                req.fade_out_sec.min(10.0)
            ));
        }
        if a_post_ops.is_empty() {
            parts.push("[acat]anull[aout]".to_string());
        } else {
            parts.push(format!("[acat]{}[aout]", a_post_ops.join(",")));
        }
    }

    Ok(BuiltFilterGraph {
        filter_complex: parts.join(";"),
        has_audio,
        output_duration_sec: out_duration_sec,
    })
}

fn resolve_active_audio_mix(
    specs: &[TrackMixSpec],
    streams: &[ProbedAudioStream],
) -> Vec<(usize, f32)> {
    if streams.is_empty() {
        return Vec::new();
    }
    if specs.is_empty() {
        let ord = find_track_ordinal(streams, TrackKind::AudioMixed).unwrap_or(0);
        return vec![(ord, 1.0)];
    }

    let mut out = Vec::new();
    for spec in specs {
        if spec.muted || spec.volume <= 0.001 {
            continue;
        }
        if let Some(ord) = find_track_ordinal(streams, spec.kind) {
            out.push((ord, spec.volume.clamp(0.0, 2.0)));
        }
    }
    if out.is_empty() && specs.iter().all(|s| !s.muted) {
        out.push((0, 1.0));
    }
    out
}

fn find_track_ordinal(streams: &[ProbedAudioStream], target: TrackKind) -> Option<usize> {
    streams
        .iter()
        .find(|s| s.track_kind == target)
        .map(|s| s.ordinal)
}

fn atempo_filters(speed: f64) -> Vec<String> {
    let mut rem = speed.clamp(0.25, 4.0);
    let mut filters = Vec::new();
    while rem > 2.0001 {
        filters.push("atempo=2.0".to_string());
        rem /= 2.0;
    }
    while rem < 0.4999 {
        filters.push("atempo=0.5".to_string());
        rem *= 2.0;
    }
    if (rem - 1.0).abs() > 0.001 {
        filters.push(format!("atempo={rem:.4}"));
    }
    filters
}

fn resolve_windows_font_escaped() -> &'static str {
    const CANDIDATES: [(&str, &str); 3] = [
        ("C:/Windows/Fonts/segoeui.ttf", "C\\:/Windows/Fonts/segoeui.ttf"),
        ("C:/Windows/Fonts/arial.ttf", "C\\:/Windows/Fonts/arial.ttf"),
        ("C:/Windows/Fonts/tahoma.ttf", "C\\:/Windows/Fonts/tahoma.ttf"),
    ];
    for (fs_path, escaped) in CANDIDATES {
        if Path::new(fs_path).is_file() {
            return escaped;
        }
    }
    "C\\:/Windows/Fonts/segoeui.ttf"
}

fn escape_drawtext(input: &str) -> String {
    input
        .replace('\\', "\\\\")
        .replace(':', "\\:")
        .replace('\'', "\\'")
        .replace('%', "\\%")
        .replace(',', "\\,")
        .replace(';', "\\;")
}

fn format_drawtext_filter(spec: &TextOverlaySpec) -> String {
    let escaped = escape_drawtext(&spec.text);
    let fontfile = resolve_windows_font_escaped();
    let x_frac = spec.x_norm.clamp(0.0, 1.0);
    let y_frac = spec.y_norm.clamp(0.0, 1.0);
    let font_size = spec.font_size.clamp(12, 160);
    let color = if spec.color_hex.trim().is_empty() {
        "#FFFFFF"
    } else {
        spec.color_hex.trim()
    };

    let mut filter = format!(
        "drawtext=fontfile='{fontfile}':text='{escaped}':fontsize={font_size}:fontcolor={color}:borderw=2:bordercolor=black@0.85:x=(w-text_w)*{x_frac:.3}:y=(h-text_h)*{y_frac:.3}"
    );
    if let (Some(s), Some(e)) = (spec.start_sec, spec.end_sec) {
        if e > s {
            filter.push_str(&format!(":enable='between(t\\,{:.3}\\,{:.3})'", s.max(0.0), e));
        }
    }
    filter
}

/// Runs a full Medal+ export matching [`AdvancedExportRequest`], trying GPU NVENC first for MP4
/// with transparent CPU `libx264` fallback, updates `.json` metadata (`is_edited = true`),
/// and optionally pushes the output to a Discord Webhook.
pub fn run_advanced_export(req: &AdvancedExportRequest) -> Result<PathBuf, String> {
    if let Some(parent) = req.output_path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent).map_err(|e| format!("create_dir_all failed: {e}"))?;
        }
    }
    let ffmpeg = resolve_sidecar_binary("ffmpeg")?;
    let probed = probe_media_streams(&req.source_path)?;
    let graph = build_advanced_filter_graph(req, &probed)?;

    if req.export_gif {
        let out = hidden_cmd(&ffmpeg)
            .args(["-y", "-hide_banner", "-loglevel", "error", "-i"])
            .arg(&req.source_path)
            .args(["-filter_complex", &graph.filter_complex, "-map", "[vout]"])
            .arg(&req.output_path)
            .output()
            .map_err(|e| format!("Failed to spawn ffmpeg GIF export: {e}"))?;
        if !out.status.success() {
            return Err(format!(
                "ffmpeg GIF export failed: {}",
                String::from_utf8_lossy(&out.stderr)
            ));
        }
    } else {
        let discord_video_kbps = req.discord_preset.and_then(|preset| {
            DiscordCompressRequest::calculate_target_video_bitrate_kbps(
                preset.target_bytes(),
                graph.output_duration_sec,
                if graph.has_audio { 128 } else { 0 },
            )
        });
        let audio_bitrate = if req.discord_preset.is_some() {
            "128k"
        } else {
            "192k"
        };

        // Prefer GPU H.264 NVENC; fall back cleanly to libx264 if NVENC rejects target params.
        let mut encoders_to_try = vec![("h264_nvenc", "p5"), ("libx264", "veryfast")];
        if discord_video_kbps.is_some() {
            encoders_to_try = vec![("h264_nvenc", "p5"), ("libx264", "medium")];
        }

        let mut last_err = String::new();
        let mut succeeded = false;

        for (vcodec, preset) in encoders_to_try {
            let mut cmd = hidden_cmd(&ffmpeg);
            cmd.args(["-y", "-hide_banner", "-loglevel", "error", "-i"])
                .arg(&req.source_path)
                .args(["-filter_complex", &graph.filter_complex, "-map", "[vout]"]);
            if graph.has_audio {
                cmd.args(["-map", "[aout]"]);
            }
            cmd.args(["-c:v", vcodec, "-preset", preset, "-pix_fmt", "yuv420p"]);
            if let Some(kbps) = discord_video_kbps {
                let bv = format!("{kbps}k");
                let maxr = format!("{}k", kbps + kbps / 4);
                let bufs = format!("{}k", kbps * 2);
                cmd.args(["-b:v", &bv, "-maxrate", &maxr, "-bufsize", &bufs]);
            } else if vcodec == "h264_nvenc" {
                cmd.args(["-rc", "vbr", "-cq", "19"]);
            } else {
                cmd.args(["-crf", "18"]);
            }
            if graph.has_audio {
                cmd.args(["-c:a", "aac", "-b:a", audio_bitrate, "-ar", "48000", "-ac", "2"]);
            }
            cmd.args(["-movflags", "+faststart"]).arg(&req.output_path);

            let out = cmd
                .output()
                .map_err(|e| format!("Failed to spawn ffmpeg ({vcodec}): {e}"))?;
            if out.status.success() {
                info!("Exported '{}' via {vcodec}", req.output_path.display());
                succeeded = true;
                break;
            }
            last_err = String::from_utf8_lossy(&out.stderr).into_owned();
            warn!("ffmpeg export attempt with {vcodec} failed, trying fallback: {last_err}");
        }

        if !succeeded {
            return Err(format!("ffmpeg export failed: {last_err}"));
        }
    }

    mark_edited_sidecar(&req.source_path, &req.output_path, req.subclip_from_session);

    if let Some(url) = req
        .discord_webhook_url
        .as_deref()
        .filter(|s| !s.trim().is_empty())
    {
        send_file_to_discord_webhook(url, &req.output_path, None)?;
    }

    Ok(req.output_path.clone())
}

fn mark_edited_sidecar(source_path: &Path, output_path: &Path, subclip_from_session: bool) {
    let src_json = ClipMetadata::sidecar_path_for(source_path);
    if let Ok(mut src_meta) = load_clip_metadata(&src_json) {
        src_meta.is_edited = true;
        let _ = save_clip_metadata(&src_meta);

        if output_path != source_path
            && output_path
                .extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| e.eq_ignore_ascii_case("mp4"))
        {
            if let Ok(probed_out) = probe_media_streams(output_path) {
                let file_size = fs::metadata(output_path).map_or(0, |m| m.len());
                let g_lower = src_meta.game_name.trim().to_ascii_lowercase();
                let clean_game = if g_lower == "screen"
                    || g_lower == "desktop"
                    || g_lower.starts_with("monitor")
                    || g_lower.starts_with("display")
                {
                    "Экран".to_string()
                } else {
                    src_meta.game_name
                };
                let new_meta = ClipMetadata {
                    id: Uuid::new_v4(),
                    title: if subclip_from_session {
                        format!("{clean_game} • Sub-clip")
                    } else {
                        format!("{clean_game} • Монтаж")
                    },
                    game_name: clean_game,
                    executable_name: src_meta.executable_name,
                    kind: if subclip_from_session {
                        RecordingKind::Clip
                    } else {
                        src_meta.kind
                    },
                    file_path: output_path.to_path_buf(),
                    thumbnail_path: None,
                    waveform_path: None,
                    created_at: Utc::now(),
                    duration_sec: probed_out.duration_sec,
                    file_size_bytes: file_size,
                    width: probed_out.width,
                    height: probed_out.height,
                    fps: src_meta.fps,
                    video_codec: VideoCodec::H264,
                    video_bitrate_kbps: src_meta.video_bitrate_kbps,
                    audio_tracks: vec![AudioTrackMetadata {
                        track_index: 1,
                        kind: TrackKind::AudioMixed,
                        label: "Mixed Audio".to_string(),
                        codec: "aac".to_string(),
                        sample_rate: 48_000,
                        channels: 2,
                        default_volume: 1.0,
                        cached_audio_path: None,
                    }],
                    markers: Vec::new(),
                    favorite: false,
                    is_edited: true,
                    tags: src_meta.tags,
                    crash_recovered: false,
                };
                let _ = save_clip_metadata(&new_meta);
            }
        }
    }
}

fn atomic_replace_and_refresh_sidecar(
    source_mp4: &Path,
    tmp_mp4: &Path,
    editor_cache_dir: &Path,
) -> Result<PathBuf, String> {
    if !tmp_mp4.is_file() {
        return Err("Temporary export file was not created".to_string());
    }

    let mut replaced = false;
    let mut last_err = String::new();
    for _ in 0..8 {
        if let Err(e) = fs::rename(tmp_mp4, source_mp4) {
            last_err = e.to_string();
            // On Windows, fs::rename may fail if destination exists and is briefly locked; try remove+rename.
            if source_mp4.exists()
                && fs::remove_file(source_mp4).is_ok()
                && fs::rename(tmp_mp4, source_mp4).is_ok()
            {
                replaced = true;
                break;
            }
            std::thread::sleep(std::time::Duration::from_millis(140));
        } else {
            replaced = true;
            break;
        }
    }

    if !replaced {
        let _ = fs::remove_file(tmp_mp4);
        return Err(format!(
            "Could not replace '{}' (file may be in use): {last_err}",
            source_mp4.display()
        ));
    }

    // Clear stale editor cache stems/thumbnails for the replaced clip.
    if let Ok(entries) = fs::read_dir(editor_cache_dir) {
        let stem = source_mp4
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("");
        for entry in entries.flatten() {
            let p = entry.path();
            if p.file_name()
                .and_then(|n| n.to_str())
                .is_some_and(|n| !stem.is_empty() && n.contains(stem))
            {
                let _ = fs::remove_file(p);
            }
        }
    }

    let thumb_path = ClipMetadata::thumbnail_path_for(source_mp4);
    let _ = fs::remove_file(&thumb_path);
    let new_thumb = generate_thumbnail_jpg(source_mp4, &thumb_path, 0.5).ok();

    let sidecar = ClipMetadata::sidecar_path_for(source_mp4);
    let legacy_sidecar = ClipMetadata::legacy_sidecar_path_for(source_mp4);
    if let Ok(mut meta) =
        load_clip_metadata(&sidecar).or_else(|_| load_clip_metadata(&legacy_sidecar))
    {
        if let Ok(probed) = probe_media_streams(source_mp4) {
            meta.duration_sec = probed.duration_sec;
            meta.width = probed.width;
            meta.height = probed.height;
        }
        meta.file_size_bytes = fs::metadata(source_mp4).map_or(meta.file_size_bytes, |m| m.len());
        meta.is_edited = true;
        if let Some(tp) = new_thumb {
            meta.thumbnail_path = Some(tp);
        } else {
            meta.thumbnail_path = None;
        }
        let _ = save_clip_metadata(&meta);
    }

    Ok(source_mp4.to_path_buf())
}

/// Lossless trims `req.source_path` into a sibling temp file and atomically replaces the original.
pub fn replace_clip_with_fast_trim(
    req: &TrimRequest,
    editor_cache_dir: &Path,
) -> Result<PathBuf, String> {
    let tmp_name = format!(
        ".{}_replacing_{}.mp4",
        req.source_path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or("clip"),
        Uuid::new_v4()
    );
    let tmp_path = req
        .source_path
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(tmp_name);
    let mut tmp_req = req.clone();
    tmp_req.output_path = tmp_path.clone();
    run_fast_trim(&tmp_req)?;
    // Remove auto-created sidecar for the temporary file name before replacing original.
    let _ = fs::remove_file(ClipMetadata::sidecar_path_for(&tmp_path));
    atomic_replace_and_refresh_sidecar(&req.source_path, &tmp_path, editor_cache_dir)
}

